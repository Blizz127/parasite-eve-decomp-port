class OverlayPostProcessTests(unittest.TestCase):
    def out(self, emitted=frozenset({"func_80190AEC"})):
        return o.post_process(OVL, "func_80190D08", TU, set(emitted), WINDOWS)

    def test_banner_names_the_overlay(self):
        out = self.out()
        self.assertIn("decomp-source-overlay: ovl_0700/func_80190D08", out)
        self.assertNotIn("decomp-source: func_80190D08", out)
        self.assertIn("src/overlays/ovl_0700/func_80190D08.c", out)
        self.assertIn("docs/evidence/ovl_0700-func_80190D08/REPORT.md", out)

    def test_leaf_and_emitted_local_callee_are_renamed(self):
        out = self.out()
        self.assertIn("#define func_80190D08 ovl_0700__func_80190D08", out)
        self.assertIn("#define func_80190AEC ovl_0700__func_80190AEC", out)
        # the rename block follows the shim include
        self.assertLess(out.index('#include "pe_guest_decomp.h"'),
                        out.index("#define func_80190D08 ovl_0700__"))

    def test_unemitted_local_callee_is_a_labelled_boundary(self):
        out = self.out()
        self.assertIn('("ovl_0700:func_80191000"', out)
        self.assertNotIn("#define func_80191000 ovl_0700__", out)

    def test_cross_overlay_callee_is_a_labelled_boundary(self):
        out = self.out()
        self.assertIn('("overlay:func_80121C04"', out)

    def test_exe_callee_keeps_its_plain_name(self):
        out = self.out()
        self.assertIn("func_80073C94();", out)
        self.assertNotIn("__func_80073C94", out)

    def test_non_emitted_local_is_not_renamed(self):
        out = self.out(emitted=frozenset())
        self.assertNotIn("#define func_80190AEC", out)

    def test_symbols_differ_per_overlay(self):
        self.assertNotEqual(o.symbol("ovl_0700", "func_8018F1E4"),
                            o.symbol("room_m0014i", "func_8018F1E4"))


