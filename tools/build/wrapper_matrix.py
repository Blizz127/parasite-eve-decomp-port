#!/usr/bin/env python3
"""Generate one audited evidence matrix for a matched wrapper family.

The input supplies function-hood evidence and relocation-normalized object
words. Span geometry, profiles, retail words, and packed words are read from
the same YAML-derived plan used by the build. Any unequal word is fatal.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import sys
from pathlib import Path
from typing import Any

from disc1_plan import PlanError, build_plan


ROOT = Path(__file__).resolve().parents[2]
WORD_RE = re.compile(r"^(?:0x)?([0-9A-Fa-f]{8})$")


class MatrixError(RuntimeError):
    """Family evidence is incomplete or non-exact."""


def words(data: bytes) -> list[int]:
    if len(data) % 4:
        raise MatrixError(f"span length {len(data)} is not word-aligned")
    return list(struct.unpack(f"<{len(data) // 4}I", data))


def parse_object_words(raw: Any, name: str) -> list[int]:
    if not isinstance(raw, list) or not raw:
        raise MatrixError(f"{name}: normalized_object_words must be non-empty")
    parsed: list[int] = []
    for value in raw:
        if not isinstance(value, str) or not (match := WORD_RE.fullmatch(value)):
            raise MatrixError(f"{name}: invalid normalized word {value!r}")
        parsed.append(int(match.group(1), 16))
    return parsed


def escape_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def generate_matrix(
    spec: dict[str, Any],
    plan: dict[str, Any],
    retail: bytes,
    candidate: bytes,
) -> str:
    if spec.get("schema_version") != 1:
        raise MatrixError("schema_version must be 1")
    title = spec.get("family")
    members = spec.get("members")
    if not isinstance(title, str) or not title.strip():
        raise MatrixError("family must be a non-empty string")
    if not isinstance(members, list) or not members:
        raise MatrixError("members must be a non-empty list")
    if candidate != retail:
        raise MatrixError("packed candidate is not globally byte-exact retail")
    if hashlib.sha1(retail).hexdigest() != plan["expected_sha1"]:
        raise MatrixError("retail image does not match the YAML SHA-1")

    by_name = {
        unit["name"]: unit
        for unit in plan["units"]
        if unit["kind"] == "c"
    }
    seen: set[str] = set()
    rows: list[tuple[dict[str, Any], str, list[int], str]] = []
    for record in members:
        if not isinstance(record, dict):
            raise MatrixError("each member must be an object")
        name = record.get("name")
        hood = record.get("function_hood")
        if name not in by_name:
            raise MatrixError(f"{name!r}: not a YAML C span")
        if name in seen:
            raise MatrixError(f"{name}: duplicate family member")
        seen.add(name)
        if not isinstance(hood, str) or not hood.strip():
            raise MatrixError(f"{name}: function_hood evidence is required")
        unit = by_name[name]
        retail_words = words(retail[unit["start"] : unit["end"]])
        packed_words = words(candidate[unit["start"] : unit["end"]])
        object_words = parse_object_words(record.get("normalized_object_words"), name)
        if len(object_words) != len(retail_words):
            raise MatrixError(
                f"{name}: normalized object has {len(object_words)} words, "
                f"YAML span has {len(retail_words)}"
            )
        if object_words != retail_words:
            mismatch = next(
                index
                for index, pair in enumerate(zip(object_words, retail_words))
                if pair[0] != pair[1]
            )
            raise MatrixError(
                f"{name}: object mismatch at word {mismatch}: "
                f"0x{object_words[mismatch]:08X} != retail 0x{retail_words[mismatch]:08X}"
            )
        if packed_words != retail_words:
            raise MatrixError(f"{name}: packed span differs from retail")
        digest = hashlib.sha256(
            retail[unit["start"] : unit["end"]]
        ).hexdigest()
        rows.append((unit, hood.strip(), retail_words, digest))

    output = [
        f"# {title} — generated wrapper-family evidence",
        "",
        "<!-- Generated by tools/build/wrapper_matrix.py. Do not edit. -->",
        "",
        f"Family members: **{len(rows)}**. Span geometry and profiles come from",
        "`configs/USA/disc1.yaml` plus `configs/USA/disc1_build_profiles.json`.",
        "The normalized single-leaf object words and final packed words equal",
        "retail for every row.",
        "",
        "| function | file span | words | build profile | function-hood evidence | span SHA-256 | result |",
        "|---|---:|---:|---|---|---|---|",
    ]
    for unit, hood, retail_words, digest in rows:
        output.append(
            f"| `{unit['name']}` | `0x{unit['start']:X}..0x{unit['end']:X}` | "
            f"{len(retail_words)} | `{unit['profile']}` | {escape_cell(hood)} | "
            f"`{digest}` | EXACT |"
        )
    for unit, _, retail_words, _ in rows:
        output.extend(
            [
                "",
                f"## `{unit['name']}` full word comparison",
                "",
                "| # | retail | normalized object | packed span |",
                "|---:|---:|---:|---:|",
            ]
        )
        for index, value in enumerate(retail_words):
            rendered = f"`0x{value:08X}`"
            output.append(f"| {index} | {rendered} | {rendered} | {rendered} |")
    output.append("")
    return "\n".join(output)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path)
    parser.add_argument("--retail", type=Path, default=ROOT / "build/extracted/disc1/SLUS_006.62")
    parser.add_argument("--candidate", type=Path, default=ROOT / "build/disc1.candidate.exe")
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", type=Path, help="fail unless this file equals generated output")
    args = parser.parse_args(argv)
    try:
        spec = json.loads(args.spec.read_text(encoding="utf-8"))
        plan = build_plan(root=ROOT)
        rendered = generate_matrix(
            spec,
            plan,
            args.retail.read_bytes(),
            args.candidate.read_bytes(),
        )
        if args.check and args.check.read_text(encoding="utf-8") != rendered:
            raise MatrixError(f"stale generated matrix: {args.check}")
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(rendered, encoding="utf-8")
        elif not args.check:
            print(rendered, end="")
    except (OSError, json.JSONDecodeError, PlanError, MatrixError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
