def fixture(exe,c):
    r,s,args=player_fixture(exe,dict(c,entry=0))
    def put(a,b):r[a:a+len(b)]=b;s[a:a+len(b)]=b
    def sw(a,v):put(a,struct.pack('<I',v&0xFFFFFFFF))
    def sh(a,v):put(a,struct.pack('<H',v&65535))
    def sb(a,v):put(a,bytes((v&255,)))
    for a in range(0xA1B30,0xA1B4C,4):sw(a,0)
    sw(0xA8034,0x180000-0xA8028);sw(0xA8038,0x182000-0xA8028);sw(0xA803C,0x184000-0xA8028)
    for t in range(7):
        sh(0xC0E28+t*2,c.get('key',20))
        for j in range(128):sw(0x182000+t*512+j*4,j*10)
    for j in range(99):
        sw(0x184000+j*24+12,0x30000+j*128);sw(0x184000+j*24+16,0x20000+j*64)
    for j in range(256):
        a=0x180000+j*32;put(a,bytes(32));sb(a+5,128);sb(a+6,j+1)
    put(0xC0E48,bytes(100));put(0xC0EAC,bytes(128*32))
    inventory=(256,257,6,10,13,17,0,0)
    for i,v in enumerate(inventory):sh(0xC0E48+i*2,v)
    for i in range(2):
        a=0xC0EAC+i*32;sb(a,1);sb(a+5,128);sb(a+6,i+1)
        if i==1 and c.get('reserve'):sb(a+20,1);sb(a+21,c['reserve'])
    sb(0xC0E20,0 if c.get('equipped',1) else 255);sb(0xC0E22,1 if c.get('equipped',1) else 255)
    sb(0xC0E0C,c.get('capacity',8));sw(0x9D018,0)
    sw(0x9D048,0x800C0E48);sw(0x9D050,min(c.get('capacity',8),50))
    sw(0x9D058,0x8009D05C);sw(0x9D064,2);sw(0x9D06C,c.get('extra',0))
    sw(0x9D038,c.get('rng',0));put(0xA1B90,bytes((i*37+19)&255 for i in range(521)))
    for i in range(3):sh(0xA1E6E+i*32,(50+i*25) if (c.get('stock_mask',7)&(1<<i)) else 0)
    sh(0x147800,c.get('category',0));sh(0x147804,c.get('amount',0))
    sw(0x942E0,0x80190000);put(0x190000,bytes(0x300))
    null=c.get('nullable',0)
    args=((c.get('item',6),),(0 if null&1 else 0x80147808,0 if null&2 else 0x8014780C),
          (0x80140000,0,c.get('icon',0)),(c.get('item',6),),(c.get('index',2),),(),
          (0x80147800,0x80147804),(0x80147808,),(c.get('extra',0),),(),(),(0x800A5D5C,))[c['entry']]
    return r,s,args

def fingerprint(r):
    h=14695981039346656037
    for a,n in RANGES:
        for b in r[a:a+n]:h=((h^b)*1099511628211)&0xFFFFFFFFFFFFFFFF
    return h

def main():
    exe=(ROOT/'build/disc1.candidate.exe').read_bytes()
    assert hashlib.sha1(exe).hexdigest()=='452fb033f2eaa4b18aa20a5bca60b8125af3a37b'
    _,s,_=fixture(exe,CASES[0]);base=words(s);common=[(i*4,v) for i,v in enumerate(base) if v]
    patches=[];cases=[]
    for k,c in enumerate(CASES):
        r,s,args=fixture(exe,c);first=len(patches)
        patches.extend((i*4,v) for i,(v,b) in enumerate(zip(words(s),base)) if v!=b)
        regs=execute(r,ENTRIES[c['entry']],args)
        result=regs[2] if c['entry'] in (3,4,5,7,8) else 0
        cases.append((c['entry'],first,len(patches),args,result,fingerprint(r)))
        print(k,c,hex(result),hex(fingerprint(r)),flush=True)
        if '--dump' in sys.argv:(ROOT/f'pc_port/build/recovery-item-oracle-{k}.bin').write_bytes(r)
    out=['/* Generated by pe_recovery_item_oracle.py --write-header. */']
    for name,rows in (('ranges',RANGES),('common',common),('patches',patches)):
        out.append(f'static const uint32_t ATK33_item_{name}[][2]={{')
        out.extend(f'    {{0x{a:X}u,0x{b:X}u}},' for a,b in rows);out.append('};')
    out.append('static const struct { unsigned entry,first,end; uint32_t args[3],result; uint64_t hash; } ATK33_item_cases[]={')
    for e,a,b,args,v,h in cases:
        params=','.join(f'0x{x&0xFFFFFFFF:08X}u' for x in args) or '0'
        out.append(f'    {{{e},{a},{b},{{{params}}},0x{v:08X}u,UINT64_C(0x{h:016X})}},')
    out.append('};')
    if '--write-header' in sys.argv:(ROOT/'pc_port/tests/retail_recovery_item_cases.h').write_text('\n'.join(out)+'\n')
    print(f'PASS: {len(cases)} original recovery / inventory / status-item cases')

if __name__=='__main__':main()
