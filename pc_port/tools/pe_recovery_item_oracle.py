"""Complete original recovery, inventory selection and status-item calls.

Equipped armor removal is excluded until the equipment-menu callbacks are
restored. Automatic recovery tests use absent effect resources, so these
fixtures validate status/item consumption rather than effect rendering.
"""
import hashlib
