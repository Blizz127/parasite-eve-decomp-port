RANGES=PLAYER_RANGES+((0xA1B30,0x470),(0xC0E00,0x1224))
ENTRIES=(0x80023E14,0x800523F8,0x8003335C,0x8005409C,0x80057D30,
         0x8005485C,0x800553A4,0x80059A40,0x80054E4C,0x80054CF8,
         0x8001F9C4,0x80020288)
CASES=[]
def case(entry=0,**kw):CASES.append(dict(entry=entry,**kw))
for item in range(5,19):
    for flags in (0,0x55,0xAA,0xFF,0x1000):case(item=item,flags=flags)
for item in range(6,18):case(item=item,battle=0,hp=2)
for item in (6,7,8,9,10):
    for hp in (1,44,45,46,32760):case(item=item,hp=hp)
for key in (0,19,20,99,990,65535):case(1,key=key)
for nullable in (1,2,3):case(1,nullable=nullable)
for icon in range(13):case(2,icon=icon)
for item in (0,1,6,7,10,13,17,256,258,999):case(3,item=item)
for index in (0,2,3,4,5):case(4,index=index)
for rng in (0,31,520):
    for equipped in (0,1):case(5,rng=rng,equipped=equipped)
for category in (0,1,2,3,4):
    for amount in (0,1,50,1000,-10,-100):case(6,category=category,amount=amount)
for stock in (0,1,2,4,7):case(6,stock_mask=stock,rng=520)
for capacity in (5,6,8,20,60):
    for reserve in (0,8,9,10):case(7,capacity=capacity,reserve=reserve)
for capacity in (5,6,8,20,60):
    for extra in (-1,0,1,2,5):case(8,capacity=capacity,extra=extra)
for extra in (0,1,2,3):case(9,extra=extra,capacity=8)
for flags in (0,1,4,16,64,128,4096,0x1055):case(10,flags=flags,armor_flags=0x8000)
for hp in (0,1,8,9,40):case(10,hp=hp,armor_flags=0x4000)
