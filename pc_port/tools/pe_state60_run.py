#!/usr/bin/env python3
"""Build and run the state60 checkers, and the mutant controls, from the repository root.

usage: pe_state60_run.py VECTOR_ROOT OUT.json [family ...]
  VECTOR_ROOT/<state60x>/<func>.txt are the vector files (pe_state60_vectors.py output).
For every family file pc_port/tools/pe_state60_<family>_check.c:
  - the build line is extracted verbatim from the file header (the ' *   cc ...' line) and executed;
  - each function's vector file is replayed in its own process (a crash shows as CRASH, not a skipped run);
  - mutant controls (all compiled from the same source with the same line + one change):
      m1: -DSTATE60_MUTANT=1  return value's low bit flipped by the harness
      m2: -DSTATE60_MUTANT=2  the first store of every case dropped by the harness
      m3: provider object replaced by a no-op object (every pe_plat_* of the 60 defined, returning 0,
          generated by this script from the declaration-only headers)
    A function is 'controlled' when at least one mutant fails at least one of its cases.
Commands, exit codes and counts are written to OUT.json."""
import json
import os
import re
import subprocess
import sys

FAMS = {'spu': 'state60a', 'ctl': 'state60b', 'gpupkt': 'state60c', 'gpuenv': 'state60d'}
SYMS = {  # header, object -> the 60's pe_plat names are taken from '#define func_X name' lines of the headers
    'state': 'pc_port/include/pe_plat/state.h', 'gpu': 'pc_port/include/pe_plat/gpu_primitive.h',
    'gpuenv': 'pc_port/include/pe_plat/gpuenv.h',
    'ctl': 'pc_port/include/pe_plat/ctl.h',
    'gpupkt': 'pc_port/include/pe_plat/gpupkt.h'}
NAMES60 = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pe_state60_vectors.py')


def sh(cmd, timeout=600):
    p = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=timeout)
    return p.returncode, p.stdout, p.stderr


def make_stub(path):
    """No-op definitions of every function in the two binding headers that the 60 map to."""
    ents = set(re.findall(r"'(func_[0-9A-F]{8})'", open(NAMES60).read()))
    out = ['/* generated by pe_state60_run.py: no-op mutant object (every pe_plat_* of the 60 returns 0) */',
           '#include <stdint.h>']
    seen = set()
    for hdr in SYMS.values():
        text = open(hdr).read()
        maps = dict((m.group(1), m.group(2)) for m in re.finditer(r'#define (func_[0-9A-F]{8}) (\w+)', text))
        decl = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
        decl = re.sub(r'\s+', ' ', decl)
        for fn, name in maps.items():
            if fn not in ents or name in seen:
                continue
            m = re.search(r'([\w ]+?\**)\s*\b%s\(([^)]*)\);' % re.escape(name), decl)
            if not m:
                raise SystemExit('no prototype for ' + name)
            seen.add(name)
            ret = m.group(1).strip()
            ret = re.sub(r'^.*;\s*', '', ret)
            body = '' if ret == 'void' else ' return 0;'
            out.append('%s %s(%s) {%s }' % (ret, name, m.group(2), body))
    open(path, 'w').write('\n'.join(out) + '\n')
    return len(seen)


def main():
    root, outp = sys.argv[1], sys.argv[2]
    fams = sys.argv[3:] or list(FAMS)
    os.makedirs('build/state60', exist_ok=True)
    log = {'commands': []}
    stub = 'build/state60/noop_stub.c'
    n = make_stub(stub)
    log['stub_functions'] = n
    for fam in fams:
        src = 'pc_port/tools/pe_state60_%s_check.c' % fam
        line = [l for l in open(src) if re.match(r' \*   cc ', l)][0][len(' *   '):].strip()
        exe = re.search(r'-o (\S+)$', line).group(1)
        builds = {'base': (line, exe)}
        builds['m1'] = (line.replace('-Wall', '-DSTATE60_MUTANT=1 -Wall').replace('-o ' + exe, '-o ' + exe + '_m1'), exe + '_m1')
        builds['m2'] = (line.replace('-Wall', '-DSTATE60_MUTANT=2 -Wall').replace('-o ' + exe, '-o ' + exe + '_m2'), exe + '_m2')
        obj = re.search(r'(build/state60/prov/\S+\.o)', line).group(1)
        stub_o = 'build/state60/noop_stub_%s.o' % fam
        rc, so, se = sh('cc -c -w %s -o %s' % (stub, stub_o))
        log['commands'].append(dict(cmd='cc -c -w %s -o %s' % (stub, stub_o), exit=rc))
        builds['m3'] = (line.replace(obj, stub_o).replace('-o ' + exe, '-o ' + exe + '_m3'), exe + '_m3')
        for k, (cmd, e) in builds.items():
            rc, so, se = sh(cmd)
            log['commands'].append(dict(cmd=cmd, exit=rc, err=se[:2000]))
            if rc:
                raise SystemExit('build %s failed: %s' % (k, se[:2000]))
        vdir = os.path.join(root, FAMS[fam])
        res = log.setdefault('functions', {})
        for fn in sorted(f for f in os.listdir(vdir) if f.startswith('func_') and f.endswith('.txt')):
            r = {}
            for k, (cmd, e) in builds.items():
                rc, so, se = sh('%s %s' % (e, os.path.join(vdir, fn)))
                m = re.search(r'checked (\d+) cases, PASS (\d+), FAIL (\d+)', so)
                r[k] = dict(exit=rc, checked=int(m.group(1)) if m else None, passed=int(m.group(2)) if m else None,
                            failed=int(m.group(3)) if m else None, status='CRASH' if (rc not in (0, 1) or not m) else ('PASS' if rc == 0 else 'FAIL'))
                r[k]['cmd'] = '%s %s' % (e, os.path.join(vdir, fn))
            r['family'] = fam
            r['controlled'] = any((r[k]['failed'] or 0) > 0 or r[k]['status'] == 'CRASH' for k in ('m1', 'm2', 'm3'))
            res[fn[:-4]] = r
            print(fn[:-4], fam, 'base', r['base']['status'], '%s/%s' % (r['base']['passed'], r['base']['checked']),
                  'm1 fail', r['m1']['failed'], 'm2 fail', r['m2']['failed'], 'm3 fail', r['m3']['failed'],
                  'controlled' if r['controlled'] else 'UNCONTROLLED', flush=True)
    json.dump(log, open(outp, 'w'), indent=1, sort_keys=True)


if __name__ == '__main__':
    main()
