RANGES=USE_RANGES+((0x178000,80),)
ENTRIES=(0x800515F8,0x800579D4,0x8004324C,0x800524D0,0x8005DC10)
CASES=[]
def case(entry=2,**kw):CASES.append(dict(entry=entry,**kw))
for pe in (-32768,-1,0,1,300,32767):
    for count in (0,1,4):case(0,pe=pe,history=count)
for maximum in (-32768,-1,0,400,32767):case(0,maximum=maximum)
for missing in (0,1,2):
    for output in (0,0x8015FA40,0x15FA40):case(0,missing=missing,output=output)
for cost in (0,1,400,0x80000000,0xFFFFFFFF):case(0,history=2,reservation=cost)
for ability in range(20):
    for discount in (0,1):case(1,ability=ability,discount=discount)
for ability in range(20):
    for battle in (0,1):
        for pe in (0,30,300):case(ability=ability,battle=battle,pe=pe)
for ability in (0,1,2,5,6,7,8,10,18,19):
    case(ability=ability,no_targets=1);case(ability=ability,hp=45)
for kind in (0,1,4,5,6,7,8,9,19,20,21):
    for ammo in (0,1):case(ability=6,kind=kind,ammo=ammo,reserve=0)
