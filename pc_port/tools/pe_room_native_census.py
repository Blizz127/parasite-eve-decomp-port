def fnv1a(b: bytes) -> int:
    h = 0x811C9DC5
    for x in b:
        h = ((h ^ x) * 0x01000193) & 0xFFFFFFFF
    return h


def w32(d: bytes, o: int) -> int:
    return struct.unpack_from("<I", d, o)[0]


def load_exe() -> bytes:
    for p in (ROOT / "build/disc1.candidate.exe", ROOT / "build/extracted/disc1/SLUS_006.62"):
        if p.is_file():
            exe = p.read_bytes()
            if hashlib.sha1(exe).hexdigest() == EXE_SHA1:
                return exe
    raise SystemExit("need the retail SLUS_006.62 (build/disc1.candidate.exe)")


def all_packages(exe: bytes) -> dict[str, dict]:
    disc = find_disc(ROOT)
    if disc is None:
        raise SystemExit("no disc image (local/pe_disc1.path or PE_DISC1_BIN)")
    out = {}
    for rec in parse_field_table(exe):
        m = rec["meta"]
        c0, c1, c2 = m & 255, (m >> 8) & 4095, m >> 20
        if c2 == 0:
            continue
        pkg = read_form1(disc, 1013 + rec["start"], c0 + c1 + c2)
        chunk2 = pkg[(c0 + c1) * 2048:(c0 + c1 + c2) * 2048]
        ex = extract_script_from_package(pkg, m)
        if ex is None:
            script, base = {"modules": []}, 0
        else:
            off, raw = ex
            script = decode_script(raw)
            base = VB + off - (c0 + c1) * 2048
        out[rec["name"]] = dict(slot=rec["index"], chunk2=chunk2, script=script, script_base=base,
                                lba=1013 + rec["start"] + c0 + c1, sectors=c2)
    return out


def text_window(chunk: bytes):
    """roomscan.py rule: back from the first `jr $ra` over non-pointer words;
    end = last `jr $ra` + delay slot.  None when the chunk holds no code."""
    ws = struct.unpack("<%dI" % (len(chunk) // 4), chunk[:len(chunk) // 4 * 4])
    jr = [i for i, w in enumerate(ws) if w == JR_RA]
    pro = [i for i, w in enumerate(ws) if (w & 0xFFFF8000) == 0x27BD8000]
    if not jr or not pro:
        return None
    i = jr[0]
    while i > 0 and not (VB <= ws[i - 1] < 0x80200000) and ws[i - 1] != 0xFFFFFFFF:
        i -= 1
    if i == 0:
        i = pro[0]
    return i * 4, (jr[-1] + 2) * 4


def bodies(chunk: bytes, lo: int, hi: int):
    ws = struct.unpack("<%dI" % (len(chunk) // 4), chunk[:len(chunk) // 4 * 4])
    out, s = [], lo // 4
    for j in range(lo // 4, hi // 4):
        if ws[j] == JR_RA:
            e = j + 2
            while s < e and ws[s] == 0:
                s += 1
            if s < e:
                out.append((s * 4, (e - s) * 4))
            s = e
    return out


def resource_records(chunk: bytes):
    """(code, descriptor) handler records: header word 1 -> table, 2-word
    records `cc 00 00 08` + room pointer (the M0374I census heuristic)."""
    tbl = w32(chunk, 4)
    recs, o = [], tbl
    while o + 8 <= len(chunk) and o <= tbl + 0x400:
        a, b = w32(chunk, o), w32(chunk, o + 4)
        if (a & 0x00FFFFFF) == 0x000008 and VB <= b < VB + len(chunk):
            recs.append((a >> 24, b))
        o += 4
    return recs


def imm_ptr_refs(chunk: bytes, lo: int, hi: int):
    """Yield (insn_off, value) for lui rt / addiu|ori rt,rt constants in the
    window that point into the chunk."""
    ws = struct.unpack("<%dI" % (len(chunk) // 4), chunk[:len(chunk) // 4 * 4])
    for i in range(lo // 4, hi // 4):
        w = ws[i]
        if (w >> 26) != 0xF:
            continue
        rt, hv = (w >> 16) & 31, w & 0xFFFF
        for j in range(i + 1, min(i + 12, hi // 4)):
            x = ws[j]
            op = x >> 26
            if op in (9, 0xD) and ((x >> 21) & 31) == rt:
                imm = x & 0xFFFF
                if op == 9 and imm >= 0x8000:
                    imm -= 0x10000
                v = ((hv << 16) + imm) & 0xFFFFFFFF
                if VB <= v < VB + len(chunk):
                    yield i * 4, v
                break
            if ((x >> 11) & 31) == rt and op == 0:   # rt overwritten by an R-type: stop
                break


def dispatch_entries(path: Path):
    """{(vma, fp): [(table, symbol, size, hand)]} from the generated registry."""
    if not path.is_file():
        return {}
    text = path.read_text(encoding="utf-8")
    out: dict = {}
    for tm in re.finditer(r"static const PeGuestCodeEntry pe_gc_(\w+)_e\[\] = \{(.*?)\n\};", text, re.S):
        # {vma, size, fp, thunk, "symbol"[, closure, thunk8, nargs]}: the
        # 5..8-argument form leaves thunk 0 and names its thunk in thunk8.
        for em in re.finditer(r"\{0x([0-9A-Fa-f]+)u, 0x([0-9A-Fa-f]+)u, 0x([0-9A-Fa-f]+)u, (\w+), \"([^\"]+)\""
                              r"(?:, 0x[0-9A-Fa-f]+u, (\w+), \d+u)?\}", tm.group(2)):
            vma, size, fp = (int(em.group(i), 16) for i in (1, 2, 3))
            thunk = em.group(4) if em.group(4) != "0" else (em.group(6) or "0")
            hand = not thunk.startswith("pe_gct_")
            out.setdefault((vma, fp), []).append((tm.group(1), em.group(5), size, hand))
    return out


def dispatch_tables(path: Path):
    """[(id, lo, hi, {vma: [(symbol, size)]})] for every registry table."""
    if not path.is_file():
        return []
    text = path.read_text(encoding="utf-8")
    spans = {m.group(1): (m.group(2), int(m.group(3), 16), int(m.group(4), 16))
             for m in re.finditer(r'PeGuestCodeTable (pe_gc_\w+) = \{"(\w+)", 0x([0-9A-F]+)u, 0x([0-9A-F]+)u', text)}
    out = []
    for tm in re.finditer(r"static const PeGuestCodeEntry (pe_gc_\w+)_e\[\] = \{(.*?)\n\};", text, re.S):
        sp = spans.get(tm.group(1))
        if not sp:
            continue
        ents: dict = {}
        for em in re.finditer(r"\{0x([0-9A-Fa-f]+)u, 0x([0-9A-Fa-f]+)u, 0x[0-9A-Fa-f]+u, \w+, \"([^\"]+)\""
                              r"(?:, 0x[0-9A-Fa-f]+u, \w+, \d+u)?\}", tm.group(2)):
            ents.setdefault(int(em.group(1), 16), []).append((em.group(3), int(em.group(2), 16)))
        out.append((sp[0], sp[1], sp[2], ents))
    return out


def host_definition(sym: str, roots) -> list[str]:
    """Host C that defines `sym`: generated TU pc_port/game/decomp/<sym>_port.c
    or a hand definition under pc_port/game/{boot,decomp_hand}.  Static text
    check only (no build); `roots` are checkout roots to search."""
    pat = re.compile(r"^(?!\s*(?:return|else)\b)(?:static\s+)?(?:unsigned\s+|signed\s+)?[A-Za-z_]\w*[\w \t\*]*\b"
                     + re.escape(sym) + r"\s*\([^;]*$", re.MULTILINE)
    out = []
    for rt in roots:
        g = rt / "pc_port/game/decomp" / f"{sym}_port.c"
        if g.is_file() and f"generated pc_port/game/decomp/{sym}_port.c" not in out:
            out.append(f"generated pc_port/game/decomp/{sym}_port.c")
    if out:
        return out
    for rt in roots:
        for sub in ("boot", "decomp_hand"):
            for p in sorted((rt / "pc_port/game" / sub).glob("*.c")):
                txt = p.read_text(encoding="utf-8", errors="replace")
                for m in pat.finditer(txt):
                    if m.group(0).rstrip().endswith("{") or "\n{" in txt[m.end():m.end() + 4]:
                        out.append(f"hand {p.relative_to(rt)}")
                        break
        if out:
            break
    return out


def yaml_leaves(path: Path):
    text = path.read_text(encoding="utf-8")
    vm = re.search(r"vram:\s*(0x[0-9A-Fa-f]+)", text)
    spans = [(int(m.group(1), 16), m.group(2), m.group(3))
             for m in re.finditer(r"^\s*-\s*\[\s*(0x[0-9A-Fa-f]+)\s*(?:,\s*(\w+)\s*(?:,\s*(\w+))?)?\s*\]",
                                  text, re.MULTILINE)]
    offs = sorted({o for o, _, _ in spans})
    out = []
    for off, kind, name in spans:
        if kind == "c" and name:
            nxt = next((o for o in offs if o > off), None)
            if nxt is not None:
                out.append((name, off, nxt - off))
    return int(vm.group(1), 16) if vm else VB, out


def nonmatching_leaves(room: str):
    """[(name, off, size)] of the room's NON_MATCHING C leaves
    (configs/USA/overlays/nonmatching.yaml); the registry carries them too."""
    path = OVL_DIR / "nonmatching.yaml"
    if not path.is_file():
        return []
    return [(m.group(1), int(m.group(2), 16), int(m.group(3), 16))
            for m in re.finditer(rf"^\s*-\s*\[\s*room_{re.escape(room)}\s*,\s*(func_\w+)\s*,"
                                 r"\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\]", path.read_text(), re.M)]


def matched_index(pkgs):
    """{(vma, size, fp): [(room, leaf, has_src)]} over every room target."""
    idx: dict = {}
    for y in sorted(OVL_DIR.glob("room_m*.yaml")):
        room = y.stem[len("room_"):]
        if room not in pkgs:
            continue
        base, leaves = yaml_leaves(y)
        blob = pkgs[room]["chunk2"]
        for name, off, size in leaves:
            if off + size > len(blob):
                continue
            src = ROOT / "src/overlays" / y.stem / f"{name}.c"
            idx.setdefault((base + off, size, fnv1a(blob[off:off + size])), []).append(
                (room, name, src.is_file()))
    return idx


def script_6a_codes(room: dict):
    """Op 0x6A allocations: [(pc, module, code_or_None)]; None = non-immediate."""
    out = []
    for m in room["script"].get("modules", []):
        for c in m["commands"]:
            if c["opcode"] == 0x6A and c["args"]:
                imm = c["args"][0] if c["modes"][0] == 0 else None
                out.append((room["script_base"] + c["offset"], m["index"], imm))
    return out


BOOT_DIR = ROOT / "pc_port/game/boot"


def direct_bindings(boot=BOOT_DIR):
    """(vma) -> list of dict(size, fnv, where) for host bindings outside the registry."""
    macros = {}
    srcs = sorted(boot.glob("*.c")) + sorted(boot.glob("*.h"))
    for f in srcs:
        for m in re.finditer(r"#define\s+(\w+)\s+\(?(0x[0-9A-Fa-f]+)u?\)?", f.read_text(errors="replace")):
            macros[m.group(1)] = int(m.group(2), 16)
    val = lambda t: macros.get(t, int(t.rstrip("uU"), 16) if t.lower().startswith("0x") else None)
    out = collections.defaultdict(list)
    tok = r"(0x[0-9A-Fa-f]+u?|\w+)"
    for f in sorted(boot.glob("*.c")):
        text = f.read_text(errors="replace")
        units = []
        for m in re.finditer(r"\n(?:int|unsigned|static int)\s+(\w+Bound)\s*\([^)]*\)\s*\{", text):
            end = text.find("\n}", m.end())
            units.append((m.start(), text[m.end():end]))
        for m in re.finditer(r"\bif\s*\(", text):
            depth, i = 1, m.end()
            while depth and i < len(text):
                depth += {"(": 1, ")": -1}.get(text[i], 0); i += 1
            units.append((m.start(), text[m.end():i]))
        for pos, body in units:
            vmas = [val(t) for t in re.findall(r"\bfn\s*==\s*" + tok, body)]
            fps = [(val(a), val(b)) for a, b in re.findall(r"PE_GuestCode_Fnv1a\(\s*fn\s*,\s*" + tok + r"\s*\)\s*==\s*" + tok, body)]
            line = text.count("\n", 0, pos) + 1
            for v in vmas:
                if v is None or not (0x8018E000 <= v < 0x801F0000):
                    continue
                where = f"{f.relative_to(ROOT)}:{line}"
                if fps:
                    for sz, fp in fps:
                        if sz is not None and fp is not None:
                            out[v].append(dict(size=sz, fnv=fp, where=where))
                else:
                    out[v].append(dict(size=None, fnv=None, where=where))
    return out


def analyse_room(name: str, room: dict, win, bs):
    """Roots + closure for one room.  Returns dict."""
    chunk = room["chunk2"]
    lo, hi = win
    starts = {VB + o: (o, s) for o, s in bs}
    by_off = sorted((o, s, VB + o) for o, s in bs)

    def containing(vma):
        off = vma - VB
        for o, s, v in by_off:
            if o <= off < o + s:
                return v
        return None

    recs = resource_records(chunk)
    allocs = script_6a_codes(room)
    used = {c for _, _, c in allocs}
    non_imm = None in used
    roots: dict[int, str] = {}
    desc = {}
    for code, d in recs:
        slots = [w32(chunk, d - VB + 4 * i) for i in range(7)]
        desc[code] = (d, slots)
        for i, s in enumerate(slots):
            if i in ALWAYS_SLOTS:
                roots.setdefault(s, f"code {code:#04x} slot {i} {SLOTS[i]} (room load/exit)")
            elif non_imm or code in used:
                sites = ",".join(f"{pc:08X}" for pc, _, c in allocs if c in (code, None))
                roots.setdefault(s, f"code {code:#04x} slot {i} {SLOTS[i]} (op 0x6A @{sites})")
    # edges
    ws = struct.unpack("<%dI" % (len(chunk) // 4), chunk[:len(chunk) // 4 * 4])
    jal_edges = collections.defaultdict(set)      # src body vma -> {dst vma}
    ext_calls = collections.defaultdict(set)      # src body vma -> {callee outside the chunk}
    for i in range(lo // 4, hi // 4):
        w = ws[i]
        if (w >> 26) == 3:
            t = ((w & 0x3FFFFFF) << 2) | 0x80000000
            src = containing(VB + i * 4)
            if VB <= t < VB + len(chunk):
                dst = containing(t)
                if src and dst and t == dst:
                    jal_edges[src].add(dst)
            elif src:
                ext_calls[src].add(t)
    ptr_edges = collections.defaultdict(set)
    table_refs = collections.defaultdict(set)
    for off, v in imm_ptr_refs(chunk, lo, hi):
        src = containing(VB + off)
        if src is None:
            continue
        if v in starts:
            ptr_edges[src].add(v)
        elif not (lo <= v - VB < hi):
            table_refs[src].add(v)
    # data words outside the text window that equal a body entry: weapon /
    # effect descriptor tables (conditional edges from every reached body)
    # Descriptor slots of records the script never instantiates are excluded
    # (their slot 0/6 roots are already handled above).
    skip_words = set()
    for code, (d, _slots) in desc.items():
        if not (non_imm or code in used):
            skip_words |= {(d - VB) // 4 + i for i in range(7)}
    TABLE_WINDOW = 64   # cap (words) on a data table addressed by reached code
    # A table ends at the next label known from code (any table reference or a
    # resource descriptor), so packed neighbours (e.g. m0065i 8018FFF8 /
    # 80190004 / 80190010 / 8019001C / descriptor 80190024) do not bleed into
    # each other.
    labels = sorted({v - VB for vs in table_refs.values() for v in vs} | {d - VB for d, _ in desc.values()})
    def table_ptrs(src):
        out = set()
        for t in table_refs.get(src, ()):
            o = t - VB
            if not (0 <= o < len(chunk)) or (lo <= o < hi):
                continue
            nxt = next((x for x in labels if x > o), len(chunk))
            for i in range(o // 4, min(o // 4 + TABLE_WINDOW, nxt // 4, len(ws))):
                if not (lo // 4 <= i < hi // 4) and i not in skip_words and ws[i] in starts:
                    out.add(ws[i])
        return out
    # BFS
    parent = {}
    queue = collections.deque()
    for r, why in roots.items():
        if r in starts:
            parent[r] = (None, why)
            queue.append(r)
    while queue:
        cur = queue.popleft()
        for dst in sorted(jal_edges[cur]):
            if dst not in parent:
                parent[dst] = (cur, f"jal from {cur:08X}")
                queue.append(dst)
        for dst in sorted(ptr_edges[cur]):
            if dst not in parent:
                parent[dst] = (cur, f"function pointer built in {cur:08X} (conditional)")
                queue.append(dst)
        for dst in sorted(table_ptrs(cur)):
            if dst not in parent:
                parent[dst] = (cur, f"pointer in a data table addressed by {cur:08X} (conditional)")
                queue.append(dst)
    return dict(records=[(c, d, s) for c, (d, s) in sorted(desc.items())], allocs=allocs, roots=roots,
                reach=parent, table_refs={k: sorted(v) for k, v in table_refs.items() if k in parent},
                ext_calls={k: sorted(v) for k, v in ext_calls.items() if k in parent})


def path_of(parent, v):
    out = []
    while v is not None:
        p, why = parent[v]
        out.append((v, why))
        v = p
    return list(reversed(out))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("room", help="room id, e.g. m0059i")
    ap.add_argument("--json", type=Path)
    ap.add_argument("--markdown", action="store_true")
    ap.add_argument("--dispatch", type=Path, default=DISPATCH)
    ap.add_argument("--skips", type=Path,
                    help="output of `gen_overlay_ports.py --rooms --check --verbose` (skip reasons)")
    ap.add_argument("--host-root", type=Path, action="append", default=[],
                    help="checkout root searched for host definitions of external callees "
                         "(default: this checkout; the generated pc_port/game/decomp TUs are git-ignored)")
    ns = ap.parse_args()
    ns.host_root = ns.host_root or [ROOT]
    exe = load_exe()
    pkgs = all_packages(exe)
    if ns.room not in pkgs:
        raise SystemExit(f"room {ns.room} has no chunk 2")
    me = pkgs[ns.room]
    win = text_window(me["chunk2"])
    if win is None:
        raise SystemExit(f"{ns.room}: no code in chunk 2")
    lo, hi = win
    bs = bodies(me["chunk2"], lo, hi)
    # family: rooms whose text window is byte-identical (same vma window)
    wh = hashlib.sha1(me["chunk2"][lo:hi]).hexdigest()
    family = sorted(r for r, p in pkgs.items()
                    if text_window(p["chunk2"]) == win and hashlib.sha1(p["chunk2"][lo:hi]).hexdigest() == wh)
    fam = {r: analyse_room(r, pkgs[r], win, bs) for r in family}
    disp = dispatch_entries(ns.dispatch)
    dbind = direct_bindings()
    midx = matched_index(pkgs)
    skips = {}
    if ns.skips and ns.skips.is_file():
        for ln in ns.skips.read_text().splitlines():
            m = re.match(r"\s+skip (room_\w+)/(func_\w+): (.*)", ln)
            if m:
                skips[(m.group(1), m.group(2))] = m.group(3)
    chunk = me["chunk2"]
    ypath = OVL_DIR / f"room_{ns.room}.yaml"
    c_spans = (yaml_leaves(ypath)[1] if ypath.is_file() else []) + nonmatching_leaves(ns.room)

    def natives_at(o):
        found = []
        for (dv, dfp), ents in disp.items():
            if dv != VB + o:
                continue
            for t, sym, esz, hand in ents:
                if o + esz <= len(chunk) and fnv1a(chunk[o:o + esz]) == dfp:
                    found.append((t, sym, esz, hand, dfp))
        return found

    rows = []
    for off, size in bs:
        vma = VB + off
        fp = fnv1a(chunk[off:off + size])
        # native: entry at this vma whose own size/fp match the room bytes
        natives = natives_at(off)
        data_head = 0
        if not natives:
            # The roomscan text-window rule folds the data words that precede
            # a room's first function (a seed, colours, a string) into its
            # first body.  When a leaf (this room's YAML c / NON_MATCHING leaf,
            # or any registry entry: how a twin room resolves the same bytes)
            # starts inside the body and ends with it, the body's code is that
            # leaf: its entry is what code and records call (the head is
            # addressed as data, e.g. m0145i `RoomFxSeed8 D_8018F1CC`).
            cands = sorted({o2 for _n, o2, s2 in c_spans if off < o2 and o2 + s2 == off + size}
                           | {dv - VB for (dv, _fp), ents in disp.items()
                              if off < dv - VB < off + size
                              and any(dv - VB + e[2] == off + size for e in ents)})
            for o2 in cands:
                tail = [x for x in natives_at(o2) if o2 + x[2] == off + size]
                if tail:
                    natives, data_head = tail, o2 - off
                    break
        # PE_GuestCode_Resolve: exactly one fingerprint match (identical 8-byte stubs count once)
        distinct = {(dfp, esz) for _, _, esz, _, dfp in natives}
        matches = len({t for t, _, _, _, _ in natives})
        if natives and (matches == 1 or (len(distinct) == 1 and next(iter(distinct))[1] == 8)):
            status = "native-hand" if any(h for *_, h, _ in natives) else "native-generated"
        elif natives:
            status = "ambiguous"
        else:
            status = "not-native"
        direct = []
        if status == "not-native":
            for b in dbind.get(vma, []):
                if b["size"] is None:
                    direct.append(b["where"] + " (address only)")
                elif off + b["size"] <= len(chunk) and fnv1a(chunk[off:off + b["size"]]) == b["fnv"]:
                    direct.append(b["where"])
            if any("(address only)" not in d for d in direct):
                status = "native-direct"
            elif direct:
                # address-only bindings are guarded by a room/overlay predicate:
                # not proof for this room, so not counted as native
                status = "direct-addr-guarded"
        mc = midx.get((vma, size, fp), [])
        reason = None
        if mc and status == "not-native":
            for room, leaf, _ in mc:
                reason = skips.get((f"room_{room}", leaf))
                if reason:
                    break
        reach_in = [r for r in family if vma in fam[r]["reach"]]
        mine = fam[ns.room]["reach"].get(vma)
        kind = None
        if mine is not None:
            kind = "conditional" if any("(conditional)" in w for _, w in path_of(fam[ns.room]["reach"], vma)) else "unconditional"
        rows.append(dict(vma=vma, off=off, size=size, fnv1a=fp, status=status, data_head=data_head,
                         direct_binding=direct, reach_kind=kind,
                         native=[f"{t}:{s}" for t, s, *_ in natives],
                         matched_c=[dict(room=r, leaf=l, src_file=s) for r, l, s in mc],
                         gen_skip_reason=reason,
                         reachable=mine is not None,
                         path=[dict(vma=v, why=w) for v, w in path_of(fam[ns.room]["reach"], vma)] if mine else [],
                         reachable_in=reach_in,
                         table_refs=[f"{x:08X}" for x in fam[ns.room]["table_refs"].get(vma, [])]))
    a = fam[ns.room]
    dtabs = dispatch_tables(ns.dispatch)
    for r in rows:
        r["external_calls"] = []
        for t in (a["ext_calls"].get(r["vma"], []) if r["reachable"] else []):
            hits = [f"{tid}:{sym}" for tid, tlo, thi, ents in dtabs if tlo <= t < thi
                    for sym, _ in ents.get(t, [])]
            r["external_calls"].append(dict(target=f"{t:08X}", registry=hits,
                                            host=host_definition(f"func_{t:08X}", ns.host_root)))
    res = dict(room=ns.room, slot=me["slot"], chunk2_lba=me["lba"], chunk2_sectors=me["sectors"],
               chunk2_size=len(chunk), chunk2_sha1=hashlib.sha1(chunk).hexdigest(),
               text_window=[lo, hi], text_window_vma=[VB + lo, VB + hi], window_sha1=wh,
               family=family, bodies=len(rows),
               records=[dict(code=c, descriptor=d, slots=s) for c, d, s in a["records"]],
               script_6a=[dict(pc=pc, module=m, code=c) for pc, m, c in a["allocs"]],
               family_records={r: [dict(code=c, descriptor=d) for c, d, _ in fam[r]["records"]] for r in family},
               family_6a={r: sorted({c for _, _, c in fam[r]["allocs"] if c is not None}) for r in family},
               dispatch_present=ns.dispatch.is_file(), rows=rows)
    if ns.json:
        ns.json.write_text(json.dumps(res, indent=1))
    n_nat = sum(1 for r in rows if r["status"].startswith("native"))
    reach = [r for r in rows if r["reachable"]]
    rnn = [r for r in reach if not r["status"].startswith("native")]
    print(f"{ns.room}: slot {me['slot']} chunk2 {len(chunk):#x} SHA-1 {res['chunk2_sha1']}; text window "
          f"[{VB+lo:08X},{VB+hi:08X}) {len(rows)} bodies; family {len(family)}: {' '.join(family)}")
    print("records: " + "; ".join(f"code {c:#04x} -> {d:08X}" for c, d, _ in a["records"])
          + " | op 0x6A: " + ", ".join(f"{pc:08X}/m{m}:{'?' if c is None else format(c, '#04x')}" for pc, m, c in a["allocs"]))
    for r in rows:
        print(f"  {r['vma']:08X} +{r['size']:#5x} fnv {r['fnv1a']:08X} {r['status']:16s} "
              f"{('REACH' + ('?' if r['reach_kind'] == 'conditional' else ' ')) if r['reachable'] else '-     '} matchedC={'y' if r['matched_c'] else 'n'}"
              + (f"  [data head {r['data_head']:#x}]" if r["data_head"] else "")
              + (f"  [{r['gen_skip_reason']}]" if r["gen_skip_reason"] else ""))
    print(f"SUMMARY: {len(rows)} bodies; {n_nat} native; {len(reach)} reachable; "
          f"{len(rnn)} reachable-not-native ({sum(r['size'] for r in rnn):#x} bytes)")
    un = [r for r in rnn if r["reach_kind"] == "unconditional"]
    print(f"REACH-KIND: reachable-not-native unconditional {len(un)}, conditional {len(rnn) - len(un)}; "
          f"native-direct {sum(1 for r in rows if r['status'] == 'native-direct')}, "
          f"direct-addr-guarded (not counted) {sum(1 for r in rows if r['status'] == 'direct-addr-guarded')}")
    for r in rows:
        if r["direct_binding"]:
            print(f"  direct binding {r['vma']:08X}: {'; '.join(r['direct_binding'])}")
    ext = collections.OrderedDict()
    for r in rnn:
        for e in r["external_calls"]:
            ext.setdefault(e["target"], dict(registry=e["registry"], host=e["host"], callers=[]))["callers"].append(f"{r['vma']:08X}")
    for t, e in sorted(ext.items()):
        print(f"  external callee {t} from {','.join(e['callers'])}: "
              + (", ".join(e["registry"]) if e["registry"] else "no registry entry")
              + " | host C: " + ("; ".join(e["host"]) if e["host"] else "NOT FOUND"))
    if ns.markdown:
        print("\n| address | size | FNV-1a | reached from | matched C | native |")
        print("|---|--:|---|---|---|---|")
        for r in sorted(rnn, key=lambda x: -x["size"]):
            mc = ", ".join(f"{m['room']}/{m['leaf']}" + ("" if m["src_file"] else " (no src file)")
                           for m in r["matched_c"][:2]) or "none"
            print(f"| {r['vma']:08X} | 0x{r['size']:X} | {r['fnv1a']:08X} | {r['path'][-1]['why']} | {mc} | {r['status']} |")
    return 0


