#!/usr/bin/env python3
"""Room-overlay native census: bodies, static reachability, native coverage.

EVIDENCE ONLY (read-only; writes nothing under the repository unless --json is
given).  Generalises the M0374I census (branch claude/helper-m0374i,
pc_port/tools/pe_m0374i_census.py) to any room package.

    python3 pc_port/tools/pe_room_native_census.py m0059i [--json out.json]
        [--markdown] [--dispatch zz_dispatch.c] [--skips gen_verbose.txt]

Inputs (the hash-checked EXE, the user's disc via the shipped readers):
  * retail SLUS_006.62 (build/disc1.candidate.exe), SHA-1 452fb033...;
  * chunk 2 (code) and chunk 1 (script) of every room package, read from the
    user's Disc 1 (PE_DISC1_BIN or local/pe_disc1.path) with
    tools/research/pe_pst0_scan.parse_field_table + pe_btl14 read_form1;
  * configs/USA/overlays/room_*.yaml (matched `c` spans) + the blobs under
    build/extracted/disc1/peimg/ (else the disc) for the matched-C index;
  * pc_port/game/decomp_ovl/_dispatch/zz_dispatch.c, generated by
    tools/analysis/gen_overlay_ports.py (git-ignored; regenerate it first,
    a stale registry gives stale answers).  Hand entries are those whose
    thunk is not a generated `pe_gct_*`.

Method (all STATIC; nothing is executed):
  1. text window + `jr $ra` bodies (roomscan.py rule), FNV-1a over the body
     (the hash PE_GuestCode_Resolve compares);
  2. handler records of the chunk resource table (`cc 00 00 08` + descriptor);
     a descriptor is 7 function slots (module-init, record-init, message,
     draw, update, teardown, room-exit; src/func_8006914C.c, func_8006F39C.c,
     func_8006F6D4.c, func_8006F8EC.c, func_8006F9F0.c, func_8006FC18.c,
     func_800696F0.c);
  3. script ops 0x6A (func_80018774 -> func_8006F39C(code)) with an
     immediate code select which records are instantiated; slots 0 and 6 of
     every record are roots regardless (room load / exit);
  4. closure over the reached bodies: `jal` to a body entry, and lui+addiu/ori
     constants that equal a body entry (function pointers stored in records);
  5. native = (vma, FNV) found in a zz_dispatch table, counted the way
     PE_GuestCode_Resolve counts (exactly one fingerprint match; 8-byte
     identical stubs count once); else native-direct when a host binding
     outside the registry binds it: a `*Bound` helper or an `if (...)` in
     pc_port/game/boot that tests `fn == VMA` with `PE_GuestCode_Fnv1a(fn,
     SIZE) == FNV` matching the room bytes (native-direct-addr when the
     binding tests the address only, e.g. overlay-guarded effect callbacks);
  6. reach kind: unconditional (slot roots, jal) vs conditional (a function
     address built as a code constant, which a command case may never store,
     or found as a data word of a weapon/effect descriptor table).
Limits are listed in docs/port/DAY2_M0059I_NATIVE_CENSUS.md.
"""
