/* retail printf (0x80071A74): the format pointer plus exactly the arguments the format consumes; the format string words are in the
 * vector's loads (so in the checker's RAM) and the conversions are counted here like the generator does (up to 3 register arguments) */
static __attribute__((unused)) unsigned fmt_args(pe_addr_t fmt)
{
    const uint8_t *p = ram + (fmt & (MEM - 1)); unsigned n = 0;
    while (*p) {
        if (*p == '%') {
            p++;
            if (*p == '%') { p++; continue; }
            while (*p && strchr("-+ #0123456789.hlL", *p)) p++;
            if (!*p) break;
            n++;
        }
        p++;
    }
    return n > 3 ? 3 : n;
}
