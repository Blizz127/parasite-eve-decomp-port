#!/usr/bin/env python3
"""Black-box vectors for the BOUNDED / RESUME behaviour of the original VLC decoder row 0x8010C89C.

Only observations are recorded.  The original reads exactly one control word in the movie module's data besides
its arguments (found by load-logging: 0x8011EB8C, 0x00FFFFFF in the shipped image) and leaves one word at 0x8011EBB4;
both are seeded/observed here.  For each (frame, bound) the original is called as the movie code would:
  call 1: a0 = frame pointer (0x80150000), a1 = arena, a2 = table;  word 0x8011EB8C = bound
  call n>1 (only while the previous call returned 1): a0 = 0 (resume), a1 = a second arena (observed to be ignored),
          bound re-seeded to the same value.
Each call records: returned v0 (1 = bounded exit, 0 = frame complete, 0xFFFFFFFF = the call did not exit within 3M instructions), the input pointer and output pointer the original
returns (relative to the call-1 a0 / a1), the word at 0x8011EBB4 (relative to a1), and the bytes the call added to the
output stream (length + FNV-1a64).  The test scenario of test_movie_updater.h (a0 = 0x80150040, all-zero stream, bound 0)
is included as synthetic case 'updater-scenario'.
Output: pc_port/tests/retail_mdec_vlc_bound_cases.h.     PE_DISC1_BIN=... python3 -I pe_mdec_vlc_bound_vectors.py [--check]
"""
import os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pe_mdec_vlc_vectors as V
from pe_movie_init_oracle import execute

OUT = 0x80160000; OUT2 = 0x80180000
BOUNDS = (0, 1, 3, 4, 13, 100, 255, 256, 1000, 4096, 0x2000, 0xFFFFFF)
BOUND_WORD = 0x11EB8C; END_WORD = 0x11EBB4


def call(r, a0, a1, bound):
    struct.pack_into('<I', r, BOUND_WORD, bound)
    st = V.Stops((0x8010CBAC, 0x8010CBBC)); st.last = 0
    try:
        g = execute(r, 0x8010C89C, (a0, a1, V.BASE_TAB, 0), stop_at=st, instruction_budget=3000000)
    except AssertionError as e:
        assert 'instruction budget' in str(e); return None
    if st.last == 0x8010CBAC:           # complete-frame exit: finish through the tail like the complete-frame oracle
        a0r, a1r = g[4], g[5]; g[9] = 0; st.last = 0
        g = execute(r, 0x8010CBB0, initial_regs=dict(enumerate(g)), stop_at=st)
        g = execute(r, 0x8010CBC0, initial_regs=dict(enumerate(g)))
        return g[2], a0r, a1r
    assert st.last == 0
    return g[2], g[4], g[5]


def chain(ram, data, frame_ptr, bound, resume=True):
    r = bytearray(ram); r[frame_ptr & 0x1FFFFF:(frame_ptr & 0x1FFFFF) + len(data)] = data
    r[0x160000:0x1A0000] = bytes([0xCD]) * 0x40000
    steps = []; prev_end = 0
    for n in range(40):
        first = n == 0
        res = call(r, frame_ptr if first else 0, OUT if first else OUT2, bound)
        if res is None:
            steps.append((0 if first else 1, 0xFFFFFFFF, 0, 0, 0, 0, 0)); break   # ret 0xFFFFFFFF = no exit within the instruction budget
        ret, a0r, a1r = res
        ret &= 0xFFFFFFFF
        end = a1r - OUT if first or True else 0
        ebb4 = (struct.unpack_from('<I', r, END_WORD)[0] - OUT) & 0xFFFFFFFF
        out = bytes(r[0x160000 + prev_end:0x160000 + end]) if end >= prev_end else b''
        steps.append((0 if first else 1, ret, (a0r - frame_ptr) & 0xFFFFFFFF, end, ebb4, len(out), V.fnv(out)))
        prev_end = max(prev_end, end)
        if ret != 1 or not resume: break
    return steps, bytes(r[0x160000:0x160000 + prev_end])


def main():
    ram, path = V.env()
    frames = V.frames_on_disc(path)
    cases = []
    for idx in (3, 500, 5000):
        cases.append(('real-frame-%d' % idx, V.read_frame(path, frames[idx])[:frames[idx]['size']], 0x80150000, idx))
    syn = dict(V.synthetic())
    for name in ('valid-v2-0', 'valid-v3-0', 'count-0', 'oddlen-6-7-100'):
        cases.append(('syn-' + name, syn[name], 0x80150000, None))
    zero = bytes(0xC) + struct.pack('<H', 0x1234) + bytes(0x40)       # the updater test record at a0 = 0x80150040 (word 0x1234 at +0xC of the frame)
    cases.append(('updater-scenario', zero, 0x80150040, None))
    L = ['/* Original libpress VLC decoder (0x8010C89C): bounded/resume call chains (black box). Generated by',
         ' * pc_port/tools/pe_mdec_vlc_bound_vectors.py.  Each step: resume flag (0 = first call with a frame pointer, 1 = a0 == 0 call),',
         ' * returned v0, returned input pointer (relative to the frame pointer), returned output pointer (relative to arena 1),',
         ' * word 0x8011EBB4 (relative to arena 1), bytes added to the output stream by the call, their FNV-1a64. */']
    rows = []; summary = []
    for name, data, ptr, idx in cases:
        full = V.run_original(ram, data, 3000000) if ptr == 0x80150000 else None
        for bound in BOUNDS:
            steps, produced = chain(ram, data, ptr, bound)
            rows.append((name, bound, ptr, len(data), V.fnv(data), steps))
            if full and steps[-1][1] == 0:
                summary.append((name, bound, len(steps), produced == full[0][:len(produced)]))
        print(name, 'done', flush=True)
    L.append('static const struct { const char *name; uint32_t bound, frame_ptr, size; uint64_t in_hash; uint32_t nsteps; uint32_t real_index; }')
    L.append('MDECVLCB_case[] = {')
    steps_all = []
    for name, bound, ptr, size, h, steps in rows:
        real = next((c[3] for c in cases if c[0] == name), None)
        n = 0 if steps is None else len(steps)
        L.append('{"%s",0x%Xu,0x%Xu,%du,UINT64_C(0x%016X),%du,%du},' % (name, bound, ptr, size, h, n, 0 if real is None else real + 1))
        if steps: steps_all += steps
    L.append('};')
    L.append('/* steps of all cases, concatenated in case order (nsteps each); a case with nsteps 0 never exited (budget) */')
    L.append('static const struct { uint32_t resume, ret, a0_rel, a1_rel, end_word_rel, added; uint64_t hash; } MDECVLCB_step[] = {')
    for s in steps_all: L.append('{%du,%du,%du,%du,%du,%du,UINT64_C(0x%016X)},' % s)
    L.append('};')
    out = '\n'.join(L) + '\n'
    p = V.ROOT / 'pc_port/tests/retail_mdec_vlc_bound_cases.h'
    if '--check' in sys.argv: assert p.read_text() == out, 'differs'
    else: p.write_text(out)
    ok = sum(1 for s in summary if s[3])
    print('PASS %d cases, %d steps; chains that completed with output equal to the complete-frame decode: %d/%d' % (len(rows), len(steps_all), ok, len(summary)))
    print('chains ending in a call that never exits:', [(r[0], hex(r[1])) for r in rows if r[5] and r[5][-1][1] == 0xFFFFFFFF])


if __name__ == '__main__':
    main()
