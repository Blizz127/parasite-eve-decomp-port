#!/usr/bin/env python3
"""Black-box retail vectors for the EXE formatter func_80071A84.

Runs the user's own retail EXE (build/disc1.candidate.exe, SHA-1 checked) in
the test-only interpreter (pe_battle_hud_oracle.execute) with the sprintf ABI
(a0 = destination, a1 = format, a2.. = argument words) and prints one row per
call: format, argument words, return value, output text.  Inputs are synthetic
formats and integers; no original instructions, source or game data are read
out or printed.  The rows are the reference for
pc_port/tests/test_bios_sprintf_retail_vectors.c.

Usage (from the repository root):
    python3 pc_port/tools/bios_sprintf_oracle.py > pc_port/tests/bios_sprintf_retail_vectors.tsv
    python3 pc_port/tools/bios_sprintf_oracle.py --check pc_port/tests/bios_sprintf_retail_vectors.tsv
"""
from pathlib import Path
import hashlib
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from pe_battle_hud_oracle import execute  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
RETAIL_SHA1 = '452fb033f2eaa4b18aa20a5bca60b8125af3a37b'
ENTRY = 0x80071A84
FMT, DST = 0x801F0000, 0x801F1000

UNSIGNED = (0, 1, 8, 42, 0x1234, 0xABCDEF, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF)
SIGNED = (0, 1, 42, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0xFFFFFFD6)
# One argument word per call.
SINGLE = (
    # plain and alternate hexadecimal (the zero rows differ from host C)
    (('%x', '%X', '%#x', '%#X', '%#.0x', '%#08x', '%#8.0X', '%#.4x', '%.0x',
      '%#-8x|', '%08x', '%8x', '%-8x|', '%hx', '%#hx'), UNSIGNED),
    # plain and alternate octal (precision-zero zero differs from host C)
    (('%o', '%#o', '%#.0o', '%#.1o', '%#.3o', '%#5.0o', '%-.0o', '%.0o',
      '%#5o', '%#05o', '%#-6o|'), UNSIGNED),
    # unsigned decimal, wide padding and precision
    (('%u', '%5u', '%-12u|', '%05u', '%.0u', '%.3u', '%hu', '%040u', '%045u',
      '%.32u', '%.33u', '%.40u', '%50.40u'), UNSIGNED),
    (('%#040x', '%#045X', '%#.40x', '%-50.40o'), (0, 1, 0x1234)),
    # signed decimal
    (('%d', '%i', '%5d', '%-5d|', '%05d', '%+d', '% d', '%+5d', '% 05d',
      '%.0d', '%.3d', '%hd', '%037d', '%038d', '%039d', '%040d', '%+045d',
      '% 040d', '%+.33d', '% .40d', '%-50.40d'), SIGNED),
    # pointers (the adapter's existing convention)
    (('%p', '%#p', '%12p|'), (0, 1, 0x2A, 0x8001ABCD)),
    (('%c', '%3c|', '%-3c|'), (0x41, 0x7A)),
    (('100%%', 'plain text'), (0,)),
)
# Several argument words per call.
MULTI = (
    ('%#x|%#o|%#08X|%#.0x', (42, 8, 42, 0)),
    ('%d %u %x %o', (0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF, 0xFFFFFFFF)),
    ('%*d|%-*d|', (6, 42, 6, 42)),
    ('%.*d|%*.*x', (4, 7, 8, 3, 0x1F)),
    ('%d/%d/%d/%d/%d/%d', (1, 2, 3, 4, 5, 6)),
)


def load_exe():
    exe = (ROOT / 'build/disc1.candidate.exe').read_bytes()
    if hashlib.sha1(exe).hexdigest() != RETAIL_SHA1:
        raise SystemExit('bios_sprintf_oracle: build/disc1.candidate.exe is not the retail EXE')
    return exe


def run(exe, fmt, values):
    ram = bytearray(0x200000)
    ram[0x10000:0x10000 + len(exe) - 0x800] = exe[0x800:]
    encoded = fmt.encode('ascii') + b'\0'
    ram[FMT & 0x1FFFFF:(FMT & 0x1FFFFF) + len(encoded)] = encoded
    start = DST & 0x1FFFFF
    ram[start:start + 512] = b'\xEE' * 512
    regs = execute(ram, ENTRY, args=(DST, FMT) + tuple(values), instruction_budget=1000000)
    end = ram.index(0, start)
    if end - start >= 500:
        raise SystemExit(f'bios_sprintf_oracle: unterminated output for {fmt!r}')
    text = bytes(ram[start:end])
    if any(b < 0x20 or b > 0x7E for b in text):
        raise SystemExit(f'bios_sprintf_oracle: non-printable output for {fmt!r} {values}')
    ret = regs[2] if regs[2] < 0x80000000 else regs[2] - 0x100000000
    return ret, text.decode('ascii')


def rows():
    exe = load_exe()
    cases = [(fmt, (value,)) for formats, values in SINGLE for fmt in formats for value in values]
    cases += list(MULTI)
    out = ['# retail func_80071A84 vectors: format<TAB>argument words (hex, comma separated)'
           '<TAB>return<TAB>[output]; generated by pc_port/tools/bios_sprintf_oracle.py']
    for fmt, values in cases:
        ret, text = run(exe, fmt, values)
        out.append('\t'.join((fmt, ','.join(f'{v:x}' for v in values), str(ret), f'[{text}]')))
    return out


def main():
    lines = rows()
    if len(sys.argv) == 3 and sys.argv[1] == '--check':
        have = Path(sys.argv[2]).read_text().splitlines()
        if have != lines:
            raise SystemExit('bios_sprintf_oracle: vector file differs from the retail EXE')
        print(f'bios_sprintf_oracle: {len(lines) - 1} vectors match the retail EXE')
        return
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
